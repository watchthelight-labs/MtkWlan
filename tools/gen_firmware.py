"""Turn the MT7925 Wi-Fi firmware in firmware/ into a C file the kext links in.

  python3 tools/gen_firmware.py <out.c>

The blobs come from linux-firmware (mediatek/mt7925, commit d5455717ead0) and are
redistributable under LICENSES/LICENCE.mediatek. Each SHA-256 is checked against
firmware/SHA256SUMS and also embedded, so the driver can publish which firmware it carries.
"""
import hashlib
import sys
from pathlib import Path

FW = Path(__file__).resolve().parents[1] / "firmware"
BLOBS = [("mtk_fw_patch", "WIFI_MT7925_PATCH_MCU_1_1_hdr.bin"),
         ("mtk_fw_ram", "WIFI_RAM_CODE_MT7925_1_1.bin")]


def pinned():
    out = {}
    for line in (FW / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2 and len(parts[0]) == 64:
            out[parts[1].lstrip("*")] = parts[0]
    return out


def main(dst):
    sums = pinned()
    lines = ["// generated by tools/gen_firmware.py from firmware/, do not edit",
             "// MediaTek MT7925 firmware, redistributable under LICENSES/LICENCE.mediatek",
             ""]
    for sym, name in BLOBS:
        data = (FW / name).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if sums.get(name) != digest:
            sys.exit(f"{name}: sha256 {digest} does not match firmware/SHA256SUMS")
        lines.append(f"const unsigned int {sym}_len = {len(data)};")
        lines.append(f'const char {sym}_sha256[] = "{digest}";')
        lines.append(f'const char {sym}_name[] = "{name}";')
        lines.append(f"const unsigned char {sym}[{len(data)}] __attribute__((aligned(16))) = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    Path(dst).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1])
